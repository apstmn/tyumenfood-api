// server/services/payments/PaymentProvider.js
//
// Единый интерфейс платёжного провайдера. Реальная платформа доставки еды
// не проводит платежи "сама" — она обязана работать через лицензированного
// эквайрера/платёжного агрегатора (в РФ, например: ЮKassa, CloudPayments,
// Т-Касса/Тинькофф Эквайринг) и соблюдать 54-ФЗ (онлайн-касса, фискальный чек
// на каждый заказ). Это не техническое ограничение, а требование закона —
// поэтому в демо-версии этот слой работает как честная имитация, а под каждым
// провайдером оставлена заглушка с описанием, что нужно для реального включения.
//
// Все провайдеры обязаны реализовывать один и тот же контракт:
//   async charge(order) -> { status: 'paid' | 'pending' | 'failed', providerRef, extra }
'use strict';

class PaymentProvider {
  // eslint-disable-next-line no-unused-vars
  async charge(order) {
    throw new Error('charge() должен быть переопределён в конкретном провайдере');
  }
}

module.exports = PaymentProvider;
