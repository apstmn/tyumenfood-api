// server/services/payments/cashOrTerminalProvider.js
// Оплата при получении: наличными курьеру/на самовывозе или картой через
// физический банковский терминал ресторана/курьера. Платформа здесь платёж
// не проводит — деньги проходят мимо неё, поэтому:
//   1) заказ создаётся со статусом payment_status = 'pending';
//   2) ресторан (или курьер) отмечает заказ оплаченным вручную после получения денег;
//   3) комиссия платформы (7%) всё равно посчитана заранее и должна быть
//      перечислена платформе отдельно (обычно — вычетом из следующих выплат
//      по безналичным заказам, либо периодическим счётом ресторану).
'use strict';

const PaymentProvider = require('./PaymentProvider');

class CashOrTerminalProvider extends PaymentProvider {
  async charge(order) {
    return {
      status: 'pending',
      providerRef: null,
      extra: {
        note: 'Оплата произойдёт при получении заказа (наличные или терминал). ' +
              'Комиссия платформы уже зафиксирована и должна быть учтена отдельно от наличной выручки.',
      },
    };
  }
}

module.exports = new CashOrTerminalProvider();
