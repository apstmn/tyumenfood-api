// Реальная схема подключения к любому агрегатору (Яндекс Еда, Яндекс Лавка,
// Купер, Broniboy и т.д.) всегда состоит из двух потоков:
//
//   1) MENU SYNC (наружу): платформа отправляет агрегатору актуальное меню
//      и остатки/доступность блюд по его API — это делает ваши рестораны
//      видимыми в приложении агрегатора.
//   2) ORDER WEBHOOK (внутрь): когда покупатель оформляет заказ в приложении
//      агрегатора, агрегатор шлёт вебхук на ваш сервер — вы обязаны принять
//      его за секунды и подтвердить/отклонить заказ.
//
// Каждый адаптер в этой папке реализует именно эти два метода. Ни один из них
// не подключён к реальному API — для этого нужна официальная регистрация
// вашего юрлица как партнёра/вендора у каждого агрегатора и получение
// боевых ключей API (см. комментарии в каждом файле-адаптере).
